#!/usr/bin/env node
// Turns a folder of Pixelarticons SVGs (MIT, https://github.com/halfmage/pixelarticons) into
// components/presentation/pixel-icons.generated.ts: icon name → path `d` on a 24×24 grid.
// The output is committed; run this only to add or change icons.
//
//   npm run icons:pixel -- <folder with *.svg>
//
// The SVGs are treated as data: only a single <path d="…"> is read from each, and anything that
// is not plain path syntax is rejected, so stray metadata (c2pa) never reaches the bundle.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import * as prettier from 'prettier';

const PATH_SYNTAX = /^[MmLlHhVvZz0-9.,\s-]+$/;

const dir = process.argv[2];
if (!dir) {
  console.error('usage: npm run icons:pixel -- <folder with *.svg>');
  process.exit(1);
}

const icons = {};
for (const file of readdirSync(resolve(dir))
  .filter((f) => f.endsWith('.svg'))
  .sort()) {
  const svg = readFileSync(join(resolve(dir), file), 'utf8');
  if (!svg.includes('viewBox="0 0 24 24"'))
    throw new Error(`${file}: expected a 24×24 viewBox`);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1)
    throw new Error(
      `${file}: expected exactly one <path>, got ${paths.length}`,
    );
  if (!PATH_SYNTAX.test(paths[0]))
    throw new Error(`${file}: unexpected characters in path data`);
  icons[basename(file, '.svg')] = paths[0];
}

const out = join(
  import.meta.dirname,
  '..',
  'components',
  'presentation',
  'pixel-icons.generated.ts',
);
const body = Object.entries(icons)
  .map(([name, d]) => `  ${JSON.stringify(name)}: ${JSON.stringify(d)},`)
  .join('\n');
const source =
  `// Generated by scripts/build-pixel-icons.mjs from Pixelarticons (MIT). Do not edit by hand.\n` +
  `export const pixelIcons = {\n${body}\n} as const;\n\n` +
  `export type PixelIconName = keyof typeof pixelIcons;\n`;
// Formatted with the repo's prettier config so regenerating gives the committed file byte for byte.
const options = (await prettier.resolveConfig(out)) ?? {};
writeFileSync(
  out,
  await prettier.format(source, { ...options, parser: 'typescript' }),
);
console.log(`${Object.keys(icons).length} icons → ${out}`);
